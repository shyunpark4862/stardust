"""Dump the public API of the pinned stardust build (site-eng/.sdbuild) as JSON and Markdown.

Run with the pinned build's interpreter, from site-eng/:
    .sdbuild/stardust/.venv/bin/python -I tools/api_inventory.py

Writes notes/api-inventory.json (full: signatures, docstrings, class members) and
API-INVENTORY.md (one line per public name with its signature and docstring summary).
The site's page list is checked against this inventory, never against the live working tree.
"""

import importlib
import inspect
import json
import pathlib
import subprocess
import sys

import stardust as sd

HERE = pathlib.Path(__file__).resolve().parent.parent
BUILD = HERE / ".sdbuild" / "stardust"

AREAS = [
    "", "linalg", "frame", "special", "stats", "random", "regression", "htest", "optimize",
    "integrate", "differentiate", "sparse", "spatial", "graph", "interpolate", "fft", "smooth",
    "plot", "cluster",
]


def kind_of(obj):
    if inspect.isclass(obj):
        return "class"
    if inspect.ismodule(obj):
        return "module"
    if callable(obj):
        return "function"
    return "value"


def signature(obj):
    # nanobind functions carry their real signature as the docstring's first line.
    doc = getattr(obj, "__doc__", "") or ""
    first = doc.strip().splitlines()[0] if doc.strip() else ""
    name = getattr(obj, "__name__", "")
    if name and first.startswith(name + "("):
        return first[len(name):]
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return None


def summary(obj):
    doc = inspect.getdoc(obj) or ""
    for line in doc.splitlines():
        if line.strip() and "(" not in line.split()[0]:
            return line.strip()
    return ""


def members(cls):
    out = {}
    for name in dir(cls):
        if name.startswith("_"):
            continue
        owner = next((b for b in cls.__mro__ if name in b.__dict__), None)
        if owner is None or (owner.__module__ == "builtins" and owner is not cls):
            continue
        try:
            attr = inspect.getattr_static(cls, name)
        except AttributeError:
            continue
        tname = type(attr).__name__
        if isinstance(attr, property) or tname in ("getset_descriptor", "nb_property", "property"):
            k = "property"
        elif isinstance(attr, (staticmethod, classmethod)) or callable(attr) or tname in (
            "nb_method", "method_descriptor", "nb_func"):
            k = "method"
        else:
            k = "attribute"
        entry = {"kind": k}
        if k == "method":
            entry["signature"] = signature(getattr(cls, name, attr))
        entry["summary"] = summary(getattr(cls, name, attr))
        out[name] = entry
    return out


commit = subprocess.run(["git", "-C", str(BUILD), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
result = {"commit": commit, "stardust_file": sd.__file__, "python": sys.version.split()[0], "areas": {}}
for area in AREAS:
    modname = "stardust" + ("." + area if area else "")
    try:
        mod = importlib.import_module(modname)
    except ImportError as exc:
        result["areas"][area or "sd"] = {"missing": str(exc)}
        continue
    has_all = hasattr(mod, "__all__")
    names = list(mod.__all__) if has_all else [n for n in dir(mod) if not n.startswith("_")]
    entries = {}
    for n in names:
        obj = getattr(mod, n, None)
        k = kind_of(obj)
        if k == "module":
            continue
        e = {"kind": k, "signature": signature(obj) if k != "value" else None, "summary": summary(obj),
             "doc": inspect.getdoc(obj) or "" if k != "value" else ""}
        if k == "class":
            e["bases"] = [b.__name__ for b in obj.__mro__[1:-1]]
            e["members"] = members(obj)
        entries[n] = e
    result["areas"][area or "sd"] = {"has_all": has_all, "names": entries}

(HERE / "notes").mkdir(exist_ok=True)
(HERE / "notes" / "api-inventory.json").write_text(json.dumps(result, indent=1, ensure_ascii=False))

lines = [
    "# API inventory",
    "",
    f"Generated by `tools/api_inventory.py` from the pinned build `{commit[:10]}` (Python {result['python']}).",
    "Full data (docstrings, class members): `notes/api-inventory.json` (not committed).",
    "",
]
for area, data in result["areas"].items():
    prefix = "sd." if area == "sd" else f"sd.{area}."
    if "missing" in data:
        lines += [f"## {prefix[:-1]} — missing", ""]
        continue
    names = data["names"]
    lines += [f"## {prefix[:-1]} ({len(names)})", ""]
    for n, e in names.items():
        sig = e["signature"] if e["signature"] and e["signature"].startswith("(") else ""
        s = f" — {e['summary']}" if e["summary"] else ""
        extra = ""
        if e["kind"] == "class":
            ms = e["members"]
            extra = f" [{sum(m['kind'] == 'method' for m in ms.values())} methods, {sum(m['kind'] != 'method' for m in ms.values())} attrs]"
        lines.append(f"- `{prefix}{n}{sig}` ({e['kind']}){extra}{s}")
    lines.append("")
(HERE / "API-INVENTORY.md").write_text("\n".join(lines))
print(sum(len(d.get("names", {})) for d in result["areas"].values()), "names")
