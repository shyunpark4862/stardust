"""Generate zeta(2), zeta(4), ..., zeta(52), each rounded to the nearest double.

Riemann zeta at an even integer has the closed form 2^(n-1) pi^n |B_n| / n!, and Boost
evaluates it that way: pow(pi, n) and the quotient lose up to 9 ULP (zeta(50) comes out
below 1). csrc/special/ops/zeta.hpp returns these values instead. Past 52, zeta(n) - 1 =
2^-n + ... is under half an ULP of 1 and the value is 1. Values from Arb (balls settled
to 2^-200), written as hexadecimal literals to csrc/special/coeffs/zeta_even.hpp.

Run: .venv/bin/python tools/gen_zeta_even.py
"""

import pathlib

import arbref
from flint import arb

LAST = 52
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/zeta_even.hpp"


def main():
    rows = []
    for n in range(2, LAST + 1, 2):
        hi, _ = arbref.to_dd(arbref.rigorous(lambda n=n: arb(n).zeta(), target=200))
        rows.append(f"    {hi.hex()},  // zeta({n}) = {hi!r}")
    hi, _ = arbref.to_dd(arbref.rigorous(lambda: arb(LAST + 2).zeta(), target=200))
    assert hi == 1.0  # the table ends where the value becomes 1
    OUT.write_text(
        "// zeta(2), zeta(4), ..., zeta(52), each rounded to the nearest double, generated by\n"
        "// tools/gen_zeta_even.py (Arb, settled to 2^-200). zeta(54) and beyond round to 1.\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::special {\n\n"
        f"inline constexpr int kZetaEvenLast = {LAST};\n"
        f"inline constexpr std::array<double, {LAST // 2}> kZetaEven = {{\n"
        + "\n".join(rows)
        + "\n};\n\n}  // namespace sd::special\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
