"""Generate Debye's polynomials U_k(p) for the uniform expansion of I_nu and K_nu (DLMF
10.41.10):

    U_0 = 1,  U_(k+1)(p) = p^2 (1 - p^2) U_k'(p) / 2 + (1/8) int_0^p (1 - 5 t^2) U_k(t) dt.

Exact rational arithmetic, then rounded to float64 (the polynomials' own coefficients, not
fitted); written to csrc/special/coeffs/debye_u.hpp. U_k has degree 3k and only the powers
p^k, p^(k+2), ..., p^(3k): stored as U_k(p) = p^k V_k(p^2), V_k's coefficients highest first
(Horner in p^2).

max |U_k| on [0, 1]: U_10 1.24, U_11 3.55: with U_0..U_10 the first omitted term is below
2e-16 relative from nu = 30.

Run: uv run python tools/gen_debye.py
"""

import pathlib
from fractions import Fraction as F

K = 10
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/debye_u.hpp"


def deriv(c):
    return [i * c[i] for i in range(1, len(c))]


def integ(c):
    return [F(0)] + [c[i] / (i + 1) for i in range(len(c))]


def mul(a, b):
    r = [F(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            r[i + j] += x * y
    return r


def add(a, b):
    n = max(len(a), len(b))
    return [(a[i] if i < len(a) else F(0)) + (b[i] if i < len(b) else F(0)) for i in range(n)]


def main():
    U = [[F(1)]]
    for _ in range(K):
        u = U[-1]
        t1 = mul([F(0), F(0), F(1, 2), F(0), F(-1, 2)], deriv(u) or [F(0)])
        t2 = [x / 8 for x in integ(mul([F(1), F(0), F(-5)], u))]
        U.append(add(t1, t2))
    rows = []
    for k, u in enumerate(U):
        assert all(u[i] == 0 for i in range(len(u)) if i < k or (i - k) % 2), k  # p^k V(p^2)
        v = [u[i] for i in range(k, len(u), 2)]  # V_k's coefficients, lowest first
        while len(v) < 2 * K + 1:
            v.append(F(0))
        rows.append("    {" + ", ".join(repr(float(c)) for c in reversed(v)) + "},  // U_" + str(k))
    OUT.write_text(f"""// Generated by tools/gen_debye.py: do not edit.
// Debye's U_k(p) = p^k V_k(p^2), k = 0..{K}: V_k's coefficients highest power first, padded
// with leading zeros to {2 * K + 1} (Horner in p^2). Exact rationals rounded to float64.
#pragma once

#include <array>

namespace sd::special {{

inline constexpr int kDebyeTerms = {K + 1};
inline constexpr std::array<std::array<double, {2 * K + 1}>, {K + 1}> kDebyeV{{{{
{chr(10).join(rows)}
}}}};

}}  // namespace sd::special
""")
    print(f"U_0..U_{K} -> {OUT}")


if __name__ == "__main__":
    main()
