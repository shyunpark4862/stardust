"""Generate the Taylor series of Ei about its positive zero x0 = 0.3725...

Ei(x0 + d) = sum_{k>=1} c_k d^k, c_k = Ei^(k)(x0) / k!, Ei'(x) = e^x / x. Near x0 the
power series gamma + log x + sum x^k / (k k!) cancels to nothing (scipy loses up to 9e4
ULP there); the Taylor series in the exact d = x - x0 does not. These are the series'
own values (mpmath, 60 digits), not fitted; written to csrc/special/coeffs/ei_taylor.hpp.
The radius of convergence is x0 (the singularity at 0): on |d| <= 0.0775 (x in
[0.3, 0.45]) the terms fall like 0.21^k, and 27 terms leave < 2^-60.

Run: uv run python tools/gen_ei_taylor.py
"""

import pathlib

import mpmath as mp

mp.mp.dps = 60
K = 27
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/ei_taylor.hpp"


def main():
    x0 = mp.findroot(mp.ei, mp.mpf("0.3725"))
    hi = float(x0)
    lo = float(x0 - mp.mpf(hi))
    c = mp.taylor(mp.ei, x0, K)  # c[0] = Ei(x0) = 0
    coefs = [mp.nstr(c[k], 22, strip_zeros=False) for k in range(K, 0, -1)]
    body = ",\n    ".join(", ".join(coefs[j : j + 3]) for j in range(0, len(coefs), 3))
    OUT.write_text(
        "// The Taylor series of Ei about its positive zero x0 (docs/learn/S5-reduce-expint-ellip.md).\n"
        "// Not fitted: the series' own values, generated by tools/gen_ei_taylor.py\n"
        "// (mpmath, 60 digits) and rounded. Highest power first, without the constant\n"
        "// term (Ei(x0) = 0): Ei(x0 + d) = d * horner(d, kEiTaylor).\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::special {\n\n"
        f"inline constexpr double kEiZeroHi = {hi!r}, kEiZeroLo = {lo!r};  // x0 = hi + lo\n\n"
        f"inline constexpr std::array<double, {K}> kEiTaylor = {{\n    {body}}};\n\n"
        "}  // namespace sd::special\n"
    )
    print(f"x0 = {mp.nstr(x0, 25)}, wrote {OUT}")


if __name__ == "__main__":
    main()
