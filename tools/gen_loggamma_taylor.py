"""Generate the series of log Gamma(1 + w) with the first J poles taken out:

    log Gamma(1 + w) = -euler w + sum_{j=1}^{J} mu(w / j) + sum_{k>=2} d_k w^k,
    mu(t) = t - log(1 + t),   d_k = (-1)^k zeta(k, J + 1) / k

(DLMF 5.7.3 with zeta(k) = sum_{j<=J} j^-k + zeta(k, J+1), the j-terms summed in closed
form.) Every part is free of cancellation away from the zeros, and the remaining series
converges for |w| < J + 1, its terms falling like (|w| / (J+1))^k.

The d_k are the Hurwitz zeta values (mpmath, 40 digits), not fitted; written to
csrc/special/coeffs/loggamma_taylor.hpp, highest power first (Horner), d_2 last.

Run: uv run python tools/gen_loggamma_taylor.py
"""

import pathlib

import mpmath as mp

mp.mp.dps = 40
J = 6
K = 50
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/loggamma_taylor.hpp"


def main():
    d = [(-1) ** k * mp.zeta(k, J + 1) / k for k in range(2, K + 1)]
    rows = ",\n".join(f"    {float(v)!r}" for v in reversed(d))
    OUT.write_text(f"""// Generated by tools/gen_loggamma_taylor.py: do not edit.
// d_k = (-1)^k zeta(k, {J + 1}) / k for k = {K}..2 (highest power first): the series of
// log Gamma(1 + w) + euler w - sum_{{j<={J}}} (w/j - log(1 + w/j)) = sum d_k w^k.
#pragma once

#include <array>

namespace sd::special {{

inline constexpr int kLoggammaJ = {J};
inline constexpr std::array<double, {K - 1}> kLoggammaTail{{
{rows}
}};

}}  // namespace sd::special
""")
    print(f"{K - 1} coefficients -> {OUT}")


if __name__ == "__main__":
    main()
