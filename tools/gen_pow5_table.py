"""Writes csrc/frame/ops/pow5_table.hpp: 5^q as 128-bit truncated fractions for
q = -342 .. 308, the table of the Eisel-Lemire float parser (docs/design/frame.md §10.4).

For q >= 0, 5^q is shifted so its top bit is bit 127 and cut to 128 bits.
For q < 0, a 128-bit approximation of 2^b / 5^-q (rounded up by one) is
used, as in Lemire's fast_float (script/table_generation.py).
"""

import pathlib

rows = []
for q in range(-342, 0):
    power5 = 5**-q
    z = 0
    while (1 << z) < power5:
        z += 1
    if q >= -27:
        c = 2 ** (z + 127) // power5 + 1
    else:
        c = 2 ** (2 * z + 2 * 64) // power5 + 1
        while c >= (1 << 128):
            c //= 2
    rows.append(c)
for q in range(0, 308 + 1):
    power5 = 5**q
    while power5 < (1 << 127):
        power5 *= 2
    while power5 >= (1 << 128):
        power5 //= 2
    rows.append(power5)

lines = [
    "// Generated by tools/gen_pow5_table.py: 5^q for q = -342 .. 308 as 128-bit",
    "// truncated fractions, high word then low word (the Eisel-Lemire table).",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace sd::frame::text {",
    "",
    "inline constexpr int kSmallestPowerOfFive = -342;",
    "inline constexpr int kLargestPowerOfFive = 308;",
    f"inline constexpr std::uint64_t kPowerOfFive128[{2 * len(rows)}] = {{",
]
for c in rows:
    lines.append(f"    0x{c >> 64:016x}, 0x{c & ((1 << 64) - 1):016x},")
lines += ["};", "", "}  // namespace sd::frame::text", ""]
out = pathlib.Path(__file__).resolve().parent.parent / "csrc" / "frame" / "ops" / "pow5_table.hpp"
out.write_text("\n".join(lines))
print(f"wrote {len(rows)} entries to {out}")
