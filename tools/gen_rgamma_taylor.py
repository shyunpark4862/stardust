"""Generate the Taylor coefficients of 1/Gamma(1 + z) about 0.

1/Gamma(1+z) = sum_k c_k z^k (entire; c_1 = euler, c_2 = euler^2/2 - pi^2/12, ...). Temme's
method for the Bessel functions (csrc/special/ops/bessel.hpp) needs
    Gamma1(mu) = (1/Gamma(1-mu) - 1/Gamma(1+mu)) / (2 mu) = -sum_{k odd} c_k mu^(k-1)
    Gamma2(mu) = (1/Gamma(1-mu) + 1/Gamma(1+mu)) / 2     =  sum_{k even} c_k mu^k
for |mu| <= 1/2, where the difference cancels as mu -> 0. These are the series' own
values (mpmath, 50 digits), not fitted (Numerical Recipes' beschb fits Chebyshev
coefficients instead). Written to csrc/special/coeffs/rgamma_taylor.hpp.

Run: uv run python tools/gen_rgamma_taylor.py
"""

import pathlib

import mpmath as mp

mp.mp.dps = 50
K = 26  # c_0 .. c_25: |c_k| 2^-k < 2^-60 beyond
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/rgamma_taylor.hpp"


def main():
    c = mp.taylor(mp.rgamma, 1, K - 1)
    odd = [c[k] for k in range(K - 1, 0, -1) if k % 2 == 1]  # c_25, ..., c_1: Gamma1 = -sum c_k mu^(k-1), in mu^2
    even = [c[k] for k in range(K - 2, -1, -1) if k % 2 == 0]  # c_24, ..., c_0: Gamma2 in mu^2
    fmt = lambda v: ",\n    ".join(", ".join(mp.nstr(x, 22, strip_zeros=False) for x in v[i : i + 3]) for i in range(0, len(v), 3))
    OUT.write_text(
        "// Taylor coefficients of 1/Gamma(1 + z) about 0, split by parity, for Temme's\n"
        "// Gamma1 and Gamma2. Not fitted: the series' own\n"
        "// values, generated by tools/gen_rgamma_taylor.py (mpmath, 50 digits) and rounded.\n"
        "// Highest power first, in mu^2:\n"
        "//     Gamma1(mu) = -horner(mu^2, kRgammaOdd),  Gamma2(mu) = horner(mu^2, kRgammaEven)\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::special {\n\n"
        f"inline constexpr std::array<double, {len(odd)}> kRgammaOdd = {{\n    {fmt(odd)}}};\n\n"
        f"inline constexpr std::array<double, {len(even)}> kRgammaEven = {{\n    {fmt(even)}}};\n\n"
        "}  // namespace sd::special\n"
    )
    print(f"c1 = {mp.nstr(c[1], 20)} (euler), wrote {OUT}")


if __name__ == "__main__":
    main()
