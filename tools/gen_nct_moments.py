"""Coefficients of the noncentral t's moment series (csrc/stats/coeffs/nct_moments.hpp).

R = sqrt(df / V), V ~ chi-square(df), x = df / 2: E[R^k] = x^(k/2) Gamma(x - k/2) / Gamma(x), and

    L_k = log E[R^k] = log Gamma(x - k/2) - log Gamma(x) + (k/2) log x
        = sum_{n>=1} (-1)^(n+1) (B_{n+1}(-k/2) - B_{n+1}(0)) / (n (n+1) x^n)

(the asymptotic series of log Gamma(x + a) - log Gamma(x) - a log x, B the Bernoulli
polynomials). The table holds, exactly as double-doubles, the coefficients of L_1 and of
D_k = L_k - k L_1 for k = 2, 3, 4 (the linear terms in log x cancel exactly; D_k is O(1/x)).

    .venv/bin/python tools/gen_nct_moments.py > csrc/stats/coeffs/nct_moments.hpp
"""

from fractions import Fraction
from math import comb

N = 60  # terms


def bernoulli_numbers(m):
    b = [Fraction(0)] * (m + 1)
    b[0] = Fraction(1)
    for n in range(1, m + 1):
        b[n] = -sum(comb(n + 1, j) * b[j] for j in range(n)) / (n + 1)
    return b


B = bernoulli_numbers(N + 2)


def bpoly(m, a):
    return sum(comb(m, j) * B[j] * a ** (m - j) for j in range(m + 1))


def lcoef(k, n):
    a = Fraction(-k, 2)
    return Fraction((-1) ** (n + 1)) * (bpoly(n + 1, a) - bpoly(n + 1, Fraction(0))) / (n * (n + 1))


def dd(q):
    hi = float(q)
    lo = float(q - Fraction(hi))
    return hi, lo


def main():
    rows = {"L1": [lcoef(1, n) for n in range(1, N + 1)]}
    for k in (2, 3, 4):
        rows[f"D{k}"] = [lcoef(k, n) - k * lcoef(1, n) for n in range(1, N + 1)]
    print("// Generated by tools/gen_nct_moments.py: the noncentral t's moment series (see there).")
    print("// kNct[r][n - 1] = coefficient of x^-n as {hi, lo}: r = 0 for L_1, r = k - 1 for D_k.")
    print("#pragma once\n\nnamespace sd::stats {\n")
    print(f"inline constexpr int kNctTerms = {N};")
    print(f"inline constexpr double kNct[4][{N}][2] = {{")
    for name in ("L1", "D2", "D3", "D4"):
        print("    {  // " + name)
        for q in rows[name]:
            hi, lo = dd(q)
            print(f"        {{{hi!r}, {lo!r}}},")
        print("    },")
    print("};\n\n}  // namespace sd::stats")


if __name__ == "__main__":
    main()
