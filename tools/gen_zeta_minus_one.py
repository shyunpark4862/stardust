"""Generate zeta(j) - 1 for j = 2..110 as double-doubles.

The Weibull moments (csrc/stats/dist/weibull.hpp) need log Gamma(1 + k x) - k log Gamma(1 + x)
for small x without cancellation, by the series
    log Gamma(1 + u) = -euler u + sum_{j>=2} (-1)^j zeta(j) u^j / j      (|u| < 1),
in which the linear terms cancel exactly. Past j = 110, zeta(j) - 1 < 2^-109: below a
double-double's last bit. Values from Arb (balls settled to 2^-200, so lo is rounded to
its last bit), written to
csrc/stats/coeffs/zeta_minus_one.hpp.

Run: .venv/bin/python tools/gen_zeta_minus_one.py
"""

import pathlib

import arbref
from flint import arb

J = 110
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/stats/coeffs/zeta_minus_one.hpp"


def main():
    rows = []
    for j in range(2, J + 1):
        hi, lo = arbref.to_dd(arbref.rigorous(lambda j=j: arb(j).zeta() - 1, target=200))
        rows.append(f"    {{{hi!r}, {lo!r}}},  // j = {j}")
    OUT.write_text(
        "// zeta(j) - 1 for j = 2..110 as double-doubles (hi, lo), generated by\n"
        "// tools/gen_zeta_minus_one.py (Arb, settled to 2^-200). Past j = 110 it is below 2^-109.\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::stats {\n\n"
        f"inline constexpr int kZetaMinusOneMax = {J};\n"
        f"inline constexpr std::array<std::array<double, 2>, {J - 1}> kZetaMinusOne = {{{{\n"
        + "\n".join(rows) + "\n}};\n\n}  // namespace sd::stats\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
