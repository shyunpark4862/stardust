"""Generate the Gauss-Legendre nodes and weights of n = 1 ... 100 points, correctly rounded
(docs/design/integrate.md §3.7, decision C42), into csrc/integrate/gauss_table.hpp.

Each node x_k (the zeros of P_n, Arb's arb.legendre_p_root) and its weight
w_k = 2 / ((1 - x_k^2) P_n'(x_k)^2) is an Arb ball settled to 2^-110 of its value
(tools/arbref.py) and rounded to the nearest double; the tool stops if a ball still holds a
rounding boundary (a value within 2^-110 of a midpoint between two doubles), where the rounding
would be a guess. Only the ceil(n/2) nonnegative nodes are written (the others are their
negatives with the same weights), ascending; the middle node of an odd n is 0 exactly.

sd.integrate.fixed_quad reads this table for n <= 100; past it, the nodes and weights are
computed at run time (csrc/integrate/gauss.cpp, stardust/integrate/_gauss.py) and the tests
compare them with the same rounding of Arb's (tests/integrate/ref/gauss.json,
tools/integrate_ref.py gauss). No mpmath.

Run: .venv/bin/python tools/gen_gauss_legendre.py
"""

from __future__ import annotations

import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import arbref  # noqa: E402

OUT = ROOT / "csrc" / "integrate" / "gauss_table.hpp"
N_MAX = 100


def _nearest(ball):
    """The double nearest the settled ball's value; ArithmeticError if the ball holds the
    midpoint between two doubles (its rounding is not determined)."""
    from flint import arb

    hi, _ = arbref.to_dd(ball)
    with arbref.precision(2600):
        for c in (math.nextafter(hi, math.inf), math.nextafter(hi, -math.inf)):
            mid = (arb(hi) + arb(c)) / 2  # exact at this precision
            if ball.contains(mid):
                raise ArithmeticError(f"{ball} holds the rounding boundary {mid}")
    return hi


def node(n: int, k: int) -> tuple[float, float]:
    """(x, w) correctly rounded: the k-th nonnegative node of n points in ascending order
    (k = 0 is the smallest, 0 itself for an odd n) and its weight."""
    from flint import arb

    j = (n - 1) // 2 - k  # arb.legendre_p_root indexes the zeros in decreasing order
    x = arbref.rigorous(lambda: arb.legendre_p_root(n, j, weight=True)[0])
    w = arbref.rigorous(lambda: arb.legendre_p_root(n, j, weight=True)[1])
    xr = 0.0 if (n % 2 == 1 and k == 0) else _nearest(x)
    return xr, _nearest(w)


def half(n: int) -> list[tuple[float, float]]:
    """The ceil(n/2) nonnegative nodes of n points with their weights, ascending."""
    return [node(n, k) for k in range((n + 1) // 2)]


def _rows(values, per=3):
    lits = [v.hex() for v in values]
    return ",\n    ".join(", ".join(lits[i : i + per]) for i in range(0, len(lits), per))


def main():
    offsets, xs, ws = [0, 0], [], []
    for n in range(1, N_MAX + 1):
        for x, w in half(n):
            xs.append(x)
            ws.append(w)
        offsets.append(len(xs))
    OUT.write_text(
        "// Gauss-Legendre nodes and weights of n = 1 ... 100 points, correctly rounded: Arb's zeros of\n"
        "// P_n and weights 2 / ((1 - x^2) P_n'(x)^2), each settled to 2^-110 and rounded to the nearest\n"
        "// double (generated by tools/gen_gauss_legendre.py; docs/design/integrate.md §3.7, C42).\n"
        "// Per n the ceil(n/2) nonnegative nodes, ascending (the others are their negatives with the\n"
        "// same weights; the middle node of an odd n is 0): entries kGaussOffset[n] to\n"
        "// kGaussOffset[n + 1] - 1.\n"
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        "namespace sd::integrate {\n\n"
        f"inline constexpr int kGaussTableMax = {N_MAX};\n\n"
        f"inline constexpr std::int32_t kGaussOffset[{len(offsets)}] = {{\n    {', '.join(map(str, offsets))}}};\n\n"
        f"inline constexpr double kGaussNodes[{len(xs)}] = {{\n    {_rows(xs)}}};\n\n"
        f"inline constexpr double kGaussWeights[{len(ws)}] = {{\n    {_rows(ws)}}};\n\n"
        "}  // namespace sd::integrate\n"
    )
    print(f"{len(xs)} nodes and weights (n <= {N_MAX}) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
