"""Generate the table of the Faddeeva function w(z) = exp(-z^2) erfc(-i z) on a grid.

csrc/special/ops/wofz.hpp sums the Taylor series of w about the nearest grid point z0:
the coefficients come from w(z0) alone by the recurrence of w' = -2 z w + 2i/sqrt(pi)
(a_{n+1} = -(2 z0 a_n + 2 a_{n-1}) / (n + 1)), so the table holds only w(z0), each part
as a double-double (hi, lo). These are the function's own values (Arb: each part a ball
settled to 2^-200 of itself, so lo is rounded to its last bit), not fitted.

The grid: z0 = i*0.1 + j*0.1 i for i = 0..70, j = 0..40, i.e. 0 <= Re z0 <= 7,
0 <= Im z0 <= 4 (the region where the continued fraction would need many terms; the
rest of the upper half plane uses the fraction). z0 is the float64 i*0.1, as in C++.
Re z < 0 by w(-conj z) = conj w(z).

Run: .venv/bin/python tools/gen_wofz_grid.py
"""

import pathlib

import arbref
from flint import acb

NX, NY, STEP = 71, 41, 0.1
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/wofz_grid.hpp"


def main():
    rows = []
    for i in range(NX):
        for j in range(NY):
            z = acb(i * STEP, j * STEP)  # i * 0.1 in float64, then exact in Arb
            w = arbref.rigorous(
                lambda z=z: (-(z * z)).exp() * (acb(0, -1) * z).erfc(), target=200, floor=arbref.DOUBLE_TINY
            )
            rh, rl = arbref.to_dd(w.real)
            ih, il = arbref.to_dd(w.imag)
            rows.append(f"    {{{rh!r}, {rl!r}, {ih!r}, {il!r}}},  // ({i}, {j})")
    text = f"""// Generated by tools/gen_wofz_grid.py: do not edit.
// w(z0) = exp(-z0^2) erfc(-i z0) at z0 = i*{STEP} + j*{STEP} i, i < {NX}, j < {NY}, row-major
// in i: {{Re hi, Re lo, Im hi, Im lo}} (double-double), from Arb balls settled to 2^-200.
#pragma once

#include <array>

namespace sd::special {{

inline constexpr int kWofzNx = {NX}, kWofzNy = {NY};
inline constexpr double kWofzStep = {STEP};
inline constexpr std::array<std::array<double, 4>, {NX * NY}> kWofzGrid{{{{
{chr(10).join(rows)}
}}}};

}}  // namespace sd::special
"""
    OUT.write_text(text)
    print(f"{NX * NY} points -> {OUT}")


if __name__ == "__main__":
    main()
