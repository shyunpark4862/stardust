"""Generate the series of the Lambert W function about its branch point -1/e.

With p = +-sqrt(2 (e x + 1)) (+ for the branch k = 0, - for k = -1),
    W = sum_k c_k p^k,  c_0 = -1, c_1 = 1, c_2 = -1/3, c_3 = 11/72, ...  (DLMF 4.13.6)
from reverting p(u) = u sqrt(2 (1 + (u - 1) e^u) / u^2), u = W + 1. These are the
series' own values, exact rationals (flint's fmpq: every step is +, -, *, / of
rationals) rounded at the end, not fitted; written to
csrc/special/coeffs/lambertw_branch.hpp. The radius of convergence is sqrt 2 (the
other branch point, x = 0 of k = -1); on |p| <= 1/2 the terms fall like 0.36^k.

Run: uv run python tools/gen_lambertw_branch.py
"""

import math
import pathlib

import arbref
from flint import fmpq

N = 40
K = 36
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/lambertw_branch.hpp"


def mul(a, b):
    r = [fmpq(0)] * N
    for i, ai in enumerate(a):
        for j in range(N - i):
            r[i + j] += ai * b[j]
    return r


def main():
    # 2 (1 + (u-1) e^u) / u^2 = sum s_k u^k: (u-1) e^u = sum (1/(k-1)! - 1/k!) u^k = sum (k-1)/k! u^k
    coef = [fmpq(k - 1, math.factorial(k)) for k in range(N + 2)]  # of u^k in (u-1)e^u
    s = [2 * coef[k + 2] for k in range(N)]  # (1 + (u-1)e^u)/u^2 times 2: starts at u^0 with 2 * 1/2 = 1
    # sqrt
    r = [fmpq(0)] * N
    r[0] = fmpq(1)
    for n in range(1, N):
        r[n] = (s[n] - sum((r[k] * r[n - k] for k in range(1, n)), fmpq(0))) / 2
    phi = [fmpq(0)] * N  # u = p phi(u): phi = 1/r
    phi[0] = 1 / r[0]
    for n in range(1, N):
        phi[n] = -sum((r[k] * phi[n - k] for k in range(1, n + 1)), fmpq(0)) / r[0]
    u = [fmpq(0)] * N  # Lagrange: [p^n] u = [u^(n-1)] phi^n / n
    pw = [fmpq(1)] + [fmpq(0)] * (N - 1)
    for n in range(1, N):
        pw = mul(pw, phi)
        u[n] = pw[n - 1] / n
    c = [u[k] for k in range(K + 1)]
    c[0] -= 1  # W = u - 1
    coefs = [arbref.nstr(c[k], 22) for k in range(K, -1, -1)]
    body = ",\n    ".join(", ".join(coefs[j : j + 3]) for j in range(0, len(coefs), 3))
    OUT.write_text(
        "// The series of Lambert W about its branch point -1/e (DLMF 4.13.6):\n"
        "//     W = sum_k c_k p^k,  p = +-sqrt(2 (e x + 1))\n"
        "// Not fitted: the series' own values, generated by tools/gen_lambertw_branch.py\n"
        "// (exact rationals) and rounded. Highest power first: W = horner(p, kLambertwBranch).\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::special {\n\n"
        f"inline constexpr std::array<double, {K + 1}> kLambertwBranch = {{\n    {body}}};\n\n"
        "}  // namespace sd::special\n"
    )
    print("c0..c3 =", [str(v) for v in c[:4]], "(expect -1, 1, -1/3, 11/72)")


if __name__ == "__main__":
    main()
