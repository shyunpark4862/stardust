"""Generate the table for the double-double logarithm (csrc/special/dd.hpp).

log(m) for m in [3/4, 3/2) is log(c) + log(1 + r), c = i/128 the nearest table point
(i = 96 .. 192) and r = (m - c)/c, |r| <= 2^-7.58. Per point: log(c) as hi + lo (hi the
nearest double, lo the rest: ~107 bits) and 1/c rounded (the reduction corrects its
rounding with one fma). mpmath, 50 digits. Written to csrc/special/coeffs/dd_log_table.hpp.

Run: uv run python tools/gen_dd_log_table.py
"""

import pathlib

import mpmath as mp

mp.mp.dps = 50
OUT = pathlib.Path(__file__).resolve().parent.parent / "csrc/special/coeffs/dd_log_table.hpp"


def main():
    rows = []
    for i in range(96, 193):
        c = mp.mpf(i) / 128
        v = mp.log(c)
        hi = float(v)
        lo = float(v - mp.mpf(hi))
        rows.append(f"    {{{hi!r}, {lo!r}, {float(1 / c)!r}}},  // c = {i}/128")
    OUT.write_text(
        "// log(c) = hi + lo and 1/c for c = i/128, i = 96 .. 192: the table of the double-double\n"
        "// logarithm (special/dd.hpp). Generated by tools/gen_dd_log_table.py (mpmath, 50 digits).\n"
        "#pragma once\n\n#include <array>\n\nnamespace sd::special::dd {\n\n"
        "struct LogPoint {\n    double hi, lo, inv;\n};\n\n"
        f"inline constexpr std::array<LogPoint, {len(rows)}> kLogTable = {{{{\n" + "\n".join(rows) + "\n}};\n\n"
        "}  // namespace sd::special::dd\n"
    )
    print(f"{len(rows)} points -> {OUT}")


if __name__ == "__main__":
    main()
