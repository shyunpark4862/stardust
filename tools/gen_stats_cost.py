"""Generate csrc/stats/cost_table.hpp: the measured per-element cost of each distribution
method, for the parallel split (csrc/stats/engine.hpp, cost_of).

The costs are the single-thread times of the official speed tables (bench/stats/t4, t5, t6:
speed.md, the `sd 1T` column: ms per 100,000 points, or ns where a table says "ns per
element"), so re-run those tables first. A table with several rows for one (distribution, method) -- parameter sets of different
cost, as the discrete distributions' small and wide supports -- gives their geometric mean.

    .venv/bin/python tools/gen_stats_cost.py
"""

import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLES = [ROOT / "bench" / "stats" / t / "speed.md" for t in ("t4", "t5", "t6")]
OUT = ROOT / "csrc" / "stats" / "cost_table.hpp"
ROW = re.compile(r"^\|\s*([A-Za-z]+)[^|]*\|\s*`(\w+)`\s*\|\s*([0-9.]+)\s*\|")


def main():
    seen = {}
    for path in TABLES:
        points = 100_000
        for line in path.read_text().splitlines():
            m = re.match(r"Arrays of (\d+) points", line)
            if m:
                points = int(m.group(1))
            if "ns per element" in line:  # a table already in ns (t5's wide parameters)
                points = 1_000_000
            m = ROW.match(line)
            if m:
                ns = float(m.group(3)) * 1e6 / points
                seen.setdefault((m.group(1).lower(), m.group(2)), []).append(max(ns, 0.5))
    rows = sorted((d, f, math.exp(sum(map(math.log, v)) / len(v))) for (d, f), v in seen.items())
    lines = [
        "// Generated by tools/gen_stats_cost.py from bench/stats/t4, t5, t6 speed.md -- do not edit.",
        "// The measured per-element cost (ns, one thread) of each distribution method, for the",
        "// parallel split (stats/engine.hpp, cost_of; special/cost.hpp).",
        "#pragma once",
        "",
        "#include <string_view>",
        "",
        "namespace sd::stats::cost_table {",
        "",
        "struct Row {",
        "    std::string_view dist, method;",
        "    double ns;",
        "};",
        "",
        f"inline constexpr Row kRows[{len(rows)}] = {{",
    ]
    lines += [f'    {{"{d}", "{f}", {ns:.3g}}},' for d, f, ns in rows]
    lines += [
        "};",
        "",
        "// The row's cost, or a negative number when the tables have no such row.",
        "constexpr double find(std::string_view dist, std::string_view method) {",
        "    for (const Row& r : kRows)",
        "        if (r.dist == dist && r.method == method) return r.ns;",
        "    return -1.0;",
        "}",
        "",
        "}  // namespace sd::stats::cost_table",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} rows")


if __name__ == "__main__":
    main()
